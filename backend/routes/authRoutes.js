const express = require('express');
const router = express.Router();
const authController = require('../controllers/authController');

// استيراد حارس الأمان (Auth Middleware)
const requireAuth = require('../middleware/authMiddleware');

// ==============================================================================
// توجيه المسارات (Modular Routing)
// لماذا؟ (Clean Architecture): 
// فصل مسارات الـ API (مثل /login و /register) في ملفات خاصة يمنع تضخم وتشوش ملف 
// السيرفر الرئيسي (server.js). كل عملية متعلقة بكيان معين (Auth) تتركز هنا.
// ==============================================================================

// مسار تسجيل الدخول (POST /login)
// تم اختيار طريقة (POST) وليس (GET) لأن بيانات المرور (كلمة السر) يجب أن تُرسل 
// داخل جسم الطلب (Body) لتكون مشفرة ومخفية، بدلاً من إرسالها مكشوفة في رابط الـ URL.
// عندما يصل طلب لهذا المسار، يتم تحويله فوراً لدالة login في الـ authController.
router.post('/login', authController.login);

// ==============================================================================
// المسار المحمي لاختبار الجلسة (GET /me)
// يمر الطلب أولاً عبر (requireAuth) للتحقق من الكوكي الآمنة المرفقة تلقائياً من المتصفح. 
// إذا نجح العبور، يقوم هذا المسار بإرجاع بيانات المستخدم (req.user) للواجهة الأمامية، 
// مما يسمح للواجهة بمعرفة من هو المسجل دون الحاجة لإعادة الدخول (مثلاً عند عمل Reload).
// ==============================================================================
router.get('/me', requireAuth, (req, res) => {
    res.json({
        message: 'الجلسة صالحة',
        user: req.user
    });
});

// ==============================================================================
// مسار تغيير كلمة المرور القائمة (PUT /change-password)
// مؤمن بشكل صارم بـ requireAuth لضمان أن المستخدم مصادق عليه ويمتلك جلسة نشطة.
// ==============================================================================
router.put('/change-password', requireAuth, authController.changePassword);

// ==============================================================================
// مسار طلب رابط استعادة كلمة المرور المفقودة (POST /forgot-password)
// مسار مفتوح عام لاستقبال طلبات الاستعادة عبر البريد الجامعي الأكاديمي.
// ==============================================================================
router.post('/forgot-password', authController.forgotPassword);

// ==============================================================================
// مسار تنفيذ تغيير واستبدال كلمة المرور بالتوكن (POST /reset-password)
// مسار مفتوح عام يطابق التوكن المشفر ويعين الكلمة الجديدة في حال صحة الطلب.
// ==============================================================================
router.post('/reset-password', authController.resetPassword);

// ==============================================================================
// مسار تسجيل الخروج الآمن وتصفير الجلسة (POST /logout)
// ==============================================================================
router.post('/logout', authController.logout);

// تصدير الموجه (Router) ليتم إرفاقه (Mount) بالسيرفر في ملف server.js
module.exports = router;
