const jwt = require('jsonwebtoken');

// ==============================================================================
// البوابة الأمنية (Auth Middleware - The Gatekeeper)
// ==============================================================================
// هذه الوظيفة (Middleware) تعمل كحارس أمن يقف قبل أي مسار محمي (Protected Route).
// وظيفتها التأكد من أن المستخدم يمتلك تصريح دخول صالح قبل السماح له بالوصول للبيانات.
// ==============================================================================

const requireAuth = (req, res, next) => {
    // 1. استخراج التوكن بأمان مطلق (XSS Immunity):
    // هنا يتجلى الإبداع الأمني؛ نحن نستخرج التوكن من (req.cookies.token) مباشرة بفضل مكتبة cookie-parser.
    // نظراً لأن التوكن مخزن كـ (HttpOnly Cookie)، فإن الجافاسكريبت في متصفح المستخدم لا يمكنه رؤيته أبداً.
    // هذا يعني أنه حتى لو نجح مهاجم في حقن كود خبيث (XSS) في الواجهة، فإنه سيستحيل عليه سرقة التوكن، 
    // لأن المتصفح هو من يرفقه تلقائياً بالطلب دون تدخل الواجهة البرمجية (Frontend JS).
    const token = req.cookies.token;

    // ==============================================================================
    // 2. معالجة حالة عدم وجود التوكن (HTTP 401 Unauthorized):
    // إذا لم يكن هناك توكن أساساً، فهذا يعني أن المستخدم لم يسجل دخوله قط، أو قام بتسجيل الخروج.
    // الكود 401 يعني "غير مصرح لك بالدخول لأننا لا نعرف من أنت".
    // ==============================================================================
    if (!token) {
        return res.status(401).json({ error: 'غير مصرح لك بالوصول، الرجاء تسجيل الدخول أولاً.' });
    }

    try {
        // ==============================================================================
        // 3. التحقق من صحة التوكن (JWT Verification):
        // نقوم بفك تشفير التوكن والتحقق من توقيعه باستخدام مفتاحنا السري (JWT_SECRET).
        // إذا تم تعديل التوكن من قبل المخترق (ولو بحرف واحد)، أو إذا انتهت صلاحيته، 
        // سترمي دالة jwt.verify() خطأ (Exception) فوراً وتنتقل لكتلة الـ catch.
        // ==============================================================================
        const decoded = jwt.verify(token, process.env.JWT_SECRET || 'super_secret_academic_key');

        // إذا كان التوكن صالحاً، نستخرج البيانات منه (مثل الـ id والـ role) ونعلقها 
        // في كائن الطلب (req.user). هذا سيتيح للوظائف التالية (Controllers) معرفة 
        // من هو المستخدم الذي يقوم بالطلب لاتخاذ قرارات الصلاحيات.
        req.user = decoded;

        // السماح للطلب بالمرور إلى المحطة التالية (Controller)
        next();
    } catch (error) {
        // ==============================================================================
        // 4. معالجة حالة التوكن التالف أو المنتهي (HTTP 403 Forbidden):
        // إذا فشل التحقق أعلاه، فإن المستخدم يمتلك توكناً (ندرك هويته)، لكن التوكن غير صالح 
        // إما لانتهاء مدته الزمنية أو لتعرضه للتلاعب.
        // الكود 403 يعني "نعرف من أنت (أو من تدعي أنك هو)، لكن الدخول ممنوع قطعاً".
        // ==============================================================================
        return res.status(403).json({ error: 'جلسة الدخول منتهية أو غير صالحة، الرجاء تسجيل الدخول مجدداً.' });
    }
};

module.exports = requireAuth;
